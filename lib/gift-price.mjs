/**
 * 明确不计价的道具（站长 2026-10-24 定：「弹幕不要算鸡腿」）。
 *
 * 🔴 「直播弹幕」是花 10 鸡腿买一次说话机会，不是送给成员的礼物，
 *    按站长要求**一律不计入鸡腿榜**，即使 App 的「总鸡腿数」把它算进去。
 *    放进这张名单是为了跟「未知价」区分开：两者 priceOf 都返回 0，
 *    但未知价要报警（新礼物上线别被静默吞掉），不计价是预期行为。
 */
const NO_PRICE = ['直播弹幕'];

const byName = new Map();
const byId = new Map();
for (const [name, id, money] of TABLE.concat(EXTRA)) {
  byName.set(name, money);
  if (id) byId.set(Number(id), money);
}

/** 名字找不到时，按前缀兜底（荧光棒各队版本价钱一样） */
function prefixMoney(name) {
  if (/^荧光棒/.test(name)) return 5;
  return 0;
}

/** 是不是「明确不计价」的道具（弹幕），调用方据此把它和未知价区分开 */
export function isNoPrice(gid, gname) {
  const n = String(gname || '').trim();
  return !!n && NO_PRICE.indexOf(n) >= 0;
}

/**
 * 查单价（鸡腿 / 个）。查不到返回 0，调用方应把这类礼物当成「未知价」单独计数，
 * 不要静默当 0 分吞掉 —— 否则新礼物上线就悄悄不计分了。
 * 用 isNoPrice() 能区分「弹幕这种明确不计价」和「真未知」。
 * @param {string|number} gid
 * @param {string} gname
 */
export function priceOf(gid, gname) {
  const n = String(gname || '').trim();
  if (n && NO_PRICE.indexOf(n) >= 0) return 0;   // 显式挡在最前，防止以后有人把它加进 TABLE
  if (n && byName.has(n)) return byName.get(n);
  const id = Number(gid) || 0;
  if (id && byId.has(id)) return byId.get(id);
  if (n) return prefixMoney(n);
  return 0;
}

/** 一次礼物记录折算多少鸡腿 */
export function giftValue(num, gid, gname) {
  const c = Math.max(1, Math.floor(Number(num) || 1));
  return c * priceOf(gid, gname);
}

/** 给前端/日志用：价目表快照 */
export function priceTable() {
  return TABLE.concat(EXTRA).map(([name, id, money]) => ({ name, id: String(id), money }));
}
